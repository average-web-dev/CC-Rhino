// Write the source of the engine's native `babel-helpers` module (see ./helpers.mjs).
//
// Usage: node src/build/babel-preset-rhino/build-helpers.mjs <output file>

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { buildHelpersModule } from "./helpers.mjs";

const output = process.argv[2];
if (!output) {
    process.stderr.write("Usage: build-helpers.mjs <output file>\n");
    process.exit(2);
}

const header = "// Generated by babel-preset-rhino/build-helpers.mjs from @babel/helpers. Do not edit.\n";
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, header + buildHelpersModule());
